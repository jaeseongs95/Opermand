package io.github.jaeseongs95.portal.store.migration;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import io.github.jaeseongs95.portal.store.sql.SqlBuilder.Database;

/** S-D0109-14: the one place where the standard SQL of the scripts is spelled the other way for a product. */
class ScriptDialectTest {

    private static final String SCRIPT = "CREATE TABLE a (id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, at TIMESTAMP NOT NULL, fine TIMESTAMP(6), now_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)";

    @Test
    @DisplayName("S-D0109-14: H2, PostgreSQL, Oracle, Db2 and SQL Server take the script as it is written")
    void standardProductsKeepTheScript() {
        for (Database product : new Database[] {Database.H2, Database.POSTGRESQL, Database.ORACLE, Database.DB2, Database.SQLSERVER}) {
            assertThat(ScriptDialect.of(product).translate(SCRIPT)).as(product.name()).isEqualTo(SCRIPT);
        }
    }

    @Test
    @DisplayName("S-D0109-14: MariaDB and MySQL spell the identity column AUTO_INCREMENT and the plain TIMESTAMP DATETIME(3); TIMESTAMP(6) and CURRENT_TIMESTAMP are not changed")
    void mariaDbAndMySqlSpellTwoPhrasesOtherwise() {
        for (Database product : new Database[] {Database.MARIADB, Database.MYSQL}) {
            assertThat(ScriptDialect.of(product).translate(SCRIPT)).as(product.name())
                .isEqualTo("CREATE TABLE a (id BIGINT AUTO_INCREMENT NOT NULL, at DATETIME(3) NOT NULL, fine TIMESTAMP(6), now_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP)");
        }
    }
}
